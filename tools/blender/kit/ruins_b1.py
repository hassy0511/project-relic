"""遺構 B1（外殻層）のキットの部品。絵：W2-06 ruins_kit_b1(_front/_side/_top/_assembled).png、ruins_mood_b1.png
寸法：spec_ruins_3d.md（2 m の格子。壁 2×0.5×4、柱 0.5×0.5×4、梁 2×0.5×0.5、管 2×0.5×0.5、手すり 2×0.5×1 など）。

部品の原点（Godot で置く位置 "pos"）は部品ごとに決めてある（PARTS の note）。どれも正面（通路側）が Godot の +Z。
  壁に付ける物（wall・door・lantern・redlight・grate・fan）  … 背面（壁に当たる面）の、下の端の中央（lantern・redlight は背面の中心）
  床に立つ物（pillar・rail・crate・sand・debris）            … 底の中央
  天井から下げる物（beam）                                     … 上の面の中央
  管（pipe・elbow・tee）                                       … 管の中心線（壁から 0.3 m 離すと金具が壁に届く）
  通路（walkway）                                               … 床板の上の面の中央
"""
from __future__ import annotations

import math

import numpy as np

from geo import Part, rot_z

G, I, B, A, R = 'graphite', 'ivory', 'brass', 'amber', 'red'


def rot(axis, deg):
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    if axis == 'x':
        M = np.array([[1, 0, 0], [0, c, -s], [0, s, c]])
    elif axis == 'y':
        M = np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])
    else:
        M = np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])
    return M


def apply(M, t=(0, 0, 0), about=(0, 0, 0)):
    about = np.asarray(about, float)
    t = np.asarray(t, float)
    return lambda v: (v - about) @ M.T + about + t


# ---------------------------------------------------------------- 共通の小部品

def post(p: Part, x, depth=0.42, h=4.0, lamp=False):
    """壁の両端の黒鉛の柱と真鍮の金具（x は柱の中心）。上下の金具は壁の上・下の面より 1 cm 外へ出す
    （柱の芯・壁の板の上の面と同じ高さだと、上から見たとき面が重なってちらつく）。芯は金具の中で止める"""
    p.box(G, (x - 0.1, -depth, 0.1), (x + 0.1, 0, h - 0.1))
    for z in (0.17, h - 0.17):
        p.cbox(B, (x, -depth * 0.55, z), (0.26, depth * 1.15, 0.36), 0.05)
    p.cbox(B, (x, -depth * 0.6, h * 0.5), (0.24, depth * 0.9, 0.2), 0.04)


def lantern(p: Part, c, mount=0.0):
    """琥珀の灯（真鍮の台と笠、琥珀のガラス）。c はガラスの中心。mount > 0 なら背面へ腕を出す"""
    x, y, z = c
    p.cyl(B, (x, y, z - 0.17), (x, y, z - 0.11), 0.085, 10)
    p.cyl(A, (x, y, z - 0.11), (x, y, z + 0.1), 0.065, 10)
    for k in range(4):
        a = math.pi / 4 + k * math.pi / 2
        p.cyl(B, (x + 0.072 * math.cos(a), y + 0.072 * math.sin(a), z - 0.11), (x + 0.072 * math.cos(a), y + 0.072 * math.sin(a), z + 0.1), 0.012, 5)
    p.lathe(B, (x, y, z + 0.1), (x, y, z + 0.2), [(0, 0.09), (0.5, 0.075), (1, 0.03)], 10)
    if mount > 0:
        p.box(G, (x - 0.03, y, z - 0.15), (x + 0.03, y + mount, z - 0.09))


def pipe_run(p: Part, x0, x1, r=0.17, y=0.0, z=0.0, segs=12):
    p.cyl(I, (x0 + 0.1, y, z), (x1 - 0.1, y, z), r, segs)
    for xe, xi in ((x0, x0 + 0.12), (x1 - 0.12, x1)):
        p.cyl(B, (xe, y, z), (xi, y, z), r + 0.055, segs)
        p.cyl(G, ((xe + xi) / 2 - 0.02, y, z), ((xe + xi) / 2 + 0.02, y, z), r + 0.07, segs)


