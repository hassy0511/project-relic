def walkway(lamp=False):
    p = Part('b1_walkway_lamp' if lamp else 'b1_walkway', '手すり付きの通路 2×2×0.3（格子の床、両側に手すり、下に垂れた配線）。原点：床の上の面の中央。'
             '当たり判定は無いので、届かない高さの飾りに使う' + ('。手前の柱に琥珀の灯' if lamp else ''))
    p.box('grate', (-1, -0.9, -0.06), (1, 0.9, 0))
    for sy in (-1, 1):
        p.box(G, (-1, sy * 0.95 - 0.06, -0.3), (1, sy * 0.95 + 0.06, 0.02))
        p.box(G, (0.85, sy * 0.95 - 0.06, 0), (0.97, sy * 0.95 + 0.06, 1.0))
        p.cbox(B, (0.91, sy * 0.95, 1.02), (0.18, 0.18, 0.08), 0.03)
        for z in (0.55, 0.95):
            p.cyl(B, (-1, sy * 0.95, z), (0.85, sy * 0.95, z), 0.024, 8)
    p.box(G, (-0.06, -0.9, -0.26), (0.06, 0.9, -0.06))
    for sy, sag in ((-0.45, 0.22), (0.35, 0.16)):
        path = [(-1 + 2 * k / 10, sy, -0.3 - sag * math.sin(math.pi * k / 10)) for k in range(11)]
        p.sweep(G, path, 0.035, 6)
    p.cbox(B, (-0.95, 0, -0.16), (0.1, 1.9, 0.3), 0.03)     # 上の面を床の格子より 1 cm 下に（同じ高さだとちらつく）
