def shaft():
    p = Part('b1_shaft', '割れ目から差す光の筋（足し合わせの半透明、長さ 7 m、下へ行くほど広がり、前へ 3 m 傾く）。原点：上の端の中心（割れ目の位置）')
    def ring(z, w, d, y):
        pts = []
        for k in range(8):
            a = 2 * math.pi * (k + 0.5) / 8
            pts.append((w * math.cos(a), y + d * math.sin(a), z))
        return pts
    p.tube('shaft', [ring(0.0, 0.8, 0.25, 0.0), ring(-3.5, 1.3, 0.8, -1.5), ring(-7.0, 1.8, 1.3, -3.0)])
    return p


