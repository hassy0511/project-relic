def pit():
    p = Part('b1_pit', '床の穴の縦穴（幅 6・長さ 1・深さ 20 m。長さは scale の z で穴に合わせる）：通路の壁の続きの白磁、下は暗い管の壁、6 m 下に赤い灯、底は見えない暗さ。'
             '原点：穴の上の端（通路の床の下の面、y -2.5）の中央')
    # 深さ 20 m：落ちたプレイヤーは y -30 で直前の足場に戻る。前は 6.5 m で底に格子があり、穴の縁から底の床が見えた
    # （落ちると格子を抜けて、縦穴の下の何も無い霧に出た）。底は暗い板だけ（縁からは霧に溶けて見えない）
    D = 20.0
    for sx in (-1, 1):
        x0, x1 = sorted((sx * 3.0, sx * 3.4))
        p.box(I, (x0, -0.5, -1.6), (x1, 0.5, 0))
        p.box('dark', (x0, -0.5, -D), (x1, 0.5, -1.6))
        xi = sx * 3.0
        for z in (-1.6, -3.6, -5.6, -8.6, -12.6):
            p.box(G, (min(xi, xi - sx * 0.08), -0.5, z - 0.1), (max(xi, xi - sx * 0.08), 0.5, z + 0.1))
        p.cyl(G, (sx * 2.75, -0.5, -2.6), (sx * 2.75, 0.5, -2.6), 0.17, 10)
        p.cyl(B, (sx * 2.72, -0.5, -4.6), (sx * 2.72, 0.5, -4.6), 0.1, 8)
        p.cyl(G, (sx * 2.75, -0.5, -10.6), (sx * 2.75, 0.5, -10.6), 0.17, 10)
        p.box(R, (min(xi, xi - sx * 0.05), -0.45, -6.25), (max(xi, xi - sx * 0.05), 0.45, -6.17))
    for sy in (-1, 1):
        y0, y1 = sorted((sy * 0.5, sy * 0.62))
        p.box('dark', (-3.4, y0, -D), (3.4, y1, 0))
        p.box(G, (-3.4, min(y0, y0 - sy * 0.04), -1.7), (3.4, max(y1, y1 - sy * 0.04), -1.5))   # 帯は壁の面から 4 cm 出す
    p.box('dark', (-3.4, -0.62, -D - 0.2), (3.4, 0.62, -D))
    return p


