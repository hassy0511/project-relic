def pipe():
    p = Part('b1_pipe', '直線の管 2×0.5×0.5（白磁、真鍮のフランジ、黒鉛の留め金）。原点：中心線。背面（+Y）へ 0.3 m の金具')
    pipe_run(p, -1, 1)
    for x in (-0.5, 0.5):
        p.cyl(G, (x - 0.07, 0, 0), (x + 0.07, 0, 0), 0.195, 12)
        p.box(G, (x - 0.05, 0.12, -0.06), (x + 0.05, 0.3, 0.06))
    return p


def elbow():
    p = Part('b1_pipe_elbow', '曲がり管 2×2×0.5（X- と背面側 Y+ にフランジ。中心線の半径 1 m）。原点：X- の端から 1 m・中心線の高さ')
    path = []
    for k in range(13):
        t = math.radians(-90 + 90 * k / 12)
        path.append((-1 + math.cos(t), 1 + math.sin(t), 0))
    # フランジの分だけ両端を詰める
    p.sweep(I, path[1:-1], 0.17, 16)
    p.cyl(I, (-1 + 0.1, 0, 0), path[1], 0.17, 16)
    p.cyl(I, path[-2], (0, 1 - 0.1, 0), 0.17, 16)
    p.cyl(B, (-1, 0, 0), (-0.88, 0, 0), 0.225, 16)
    p.cyl(B, (0, 0.88, 0), (0, 1, 0), 0.225, 16)
    mid = path[6]
    t = np.array(path[7]) - np.array(path[5])
    t = t / np.linalg.norm(t)
    p.cyl(G, np.array(mid) - t * 0.07, np.array(mid) + t * 0.07, 0.195, 16)
    return p


