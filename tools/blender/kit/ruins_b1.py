def wall(name='b1_wall', fitted=True):
    p = Part(name, '壁 2×0.5×4。原点：背面の下の端の中央。fitted：左の柱に細い管、右の柱に赤い非常灯')
    p.box(G, (-1, -0.1, 0), (1, 0, 4))
    p.box(G, (-0.8, -0.32, 0), (0.8, 0, 0.32))
    p.box(B, (-0.8, -0.335, 0.27), (0.8, -0.315, 0.3))
    p.box(G, (-0.8, -0.3, 3.72), (0.8, 0, 4))
    post(p, -0.9)
    post(p, 0.9)
    for x0, x1 in ((-0.78, -0.02), (0.02, 0.78)):
        for z0, z1 in ((0.34, 1.42), (1.46, 2.58), (2.62, 3.70)):
            p.cbox(I, ((x0 + x1) / 2, -0.15, (z0 + z1) / 2), (x1 - x0, 0.1, z1 - z0), 0.035, 'y')
    if fitted:
        p.cyl(G, (-0.9, -0.47, 0.36), (-0.9, -0.47, 3.68), 0.045, 8)
        for z in (1.0, 2.7):
            p.cyl(B, (-0.9, -0.47, z - 0.05), (-0.9, -0.47, z + 0.05), 0.065, 8)
        p.box(G, (0.83, -0.44, 2.1), (0.97, -0.41, 3.0))
        p.box(R, (0.865, -0.46, 2.18), (0.935, -0.44, 2.92))
    return p


