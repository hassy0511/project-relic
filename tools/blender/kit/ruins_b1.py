def pillar():
    p = Part('b1_pillar', '柱 0.5×0.5×4（真鍮の台と冠）。原点：底の中央')
    # 黒鉛の芯は冠の中（3.7 m）で止める。前は芯の上の面が冠の上の面と同じ 4.0 m で、冠の上に縞の三角形がちらついた
    p.box(G, (-0.2, -0.2, 0), (0.2, 0.2, 3.7))
    p.box(G, (-0.34, -0.34, 0), (0.34, 0.34, 0.08))
    p.cbox(B, (0, 0, 0.24), (0.6, 0.6, 0.34), 0.08)
    p.cbox(B, (0, 0, 3.8), (0.56, 0.56, 0.4), 0.07)
    p.cbox(B, (0, 0, 2.0), (0.5, 0.5, 0.14), 0.04)
    for k in range(4):
        M = rot('z', 90 * k)
        n0 = len(p.pieces)
        for z0, z1 in ((0.45, 1.9), (2.1, 3.55)):
            p.cbox(I, (0, -0.215, (z0 + z1) / 2), (0.28, 0.05, z1 - z0), 0.03, 'y')
        p.cyl(G, (-0.205, -0.205, 0.42), (-0.205, -0.205, 3.58), 0.035, 6)
        p.transformed(apply(M), n0)
    return p


