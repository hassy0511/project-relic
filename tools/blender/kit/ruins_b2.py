            p.cyl(P, (-W / 2 + 0.12, sy * (D / 2 - r), z), (W / 2 - 0.12, sy * (D / 2 - r), z), r, 10)
            for bx in (-1.0, 1.0):
                p.cyl(B, (bx - 0.06, sy * (D / 2 - r), z), (bx + 0.06, sy * (D / 2 - r), z), r + 0.03, 10)
