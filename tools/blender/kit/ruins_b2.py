# ---------------------------------------------------------------- 共通の小部品

def fat_pipe_x(p: Part, x0, x1, z, r=0.27, y=-0.04, bands=(-0.55, 0.55), segs=12):
    """壁に沿った太い管（x0〜x1、中心の高さ z）。真鍮の帯は管より 0.035 太い"""
    p.cyl(P, (x0, y, z), (x1, y, z), r, segs)
    for bx in bands:
        if x0 + 0.08 < bx < x1 - 0.08:
            p.cyl(B, (bx - 0.08, y, z), (bx + 0.08, y, z), r + 0.035, segs)


def b2_post(p: Part, x, h=4.0, w=0.24, depth=0.32, red=True, lamp=True):
    """白磁の支柱（壁の部品の両端）：黒鉛の留め金、赤い非常灯の縦の筋、足元の琥珀の小さな灯。灯の下は汚れた白磁（ivory_stain）"""
    # 柱は 3 段：足元（汚れ）・中（灯の下の汚れ）・上（白磁）
    p.cbox(IS, (x, -depth / 2, 0.75), (w, depth, 1.1), 0.03)
    p.cbox(IS, (x, -depth / 2, 1.85), (w, depth, 1.0), 0.03)
    p.cbox(I, (x, -depth / 2, 3.05), (w, depth, 1.3), 0.03)
    for z in (0.2, 1.3, 2.4, 3.78):
        hz = 0.07 if z not in (0.2, 3.78) else 0.2
        p.box(G, (x - w / 2 - 0.02, -depth - 0.005, z - hz), (x + w / 2 + 0.02, 0.0, z + hz))
    if red:
        p.box(G, (x - 0.05, -depth - 0.006, 2.45), (x + 0.05, -depth + 0.02, 3.2))
        p.box(R, (x - 0.028, -depth - 0.016, 2.5), (x + 0.028, -depth - 0.004, 3.15))
    if lamp:
        p.cbox(B, (x, -depth + 0.005, 0.62), (0.12, 0.03, 0.16), 0.01)
        p.box(A, (x - 0.035, -depth - 0.016, 0.57), (x + 0.035, -depth - 0.008, 0.67))


def frame_rails(p: Part):
    """壁の区画の黒鉛の枠：足元の台（真鍮の帯）と上の枠"""
    p.box(G, (-1, -0.2, 0), (1, 0, 0.36))
    p.box(B, (-1, -0.215, 0.3), (1, -0.195, 0.33))
    p.box(G, (-1, -0.2, 3.62), (1, 0, 4.0))
    p.box(B, (-1, -0.215, 3.65), (1, -0.195, 3.68))


