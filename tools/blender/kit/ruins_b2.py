def seal_ring():
    p = Part('b2_seal_ring', '封印室の可動リング（台座の上 3.4 m の黒鉛と真鍮の輪 直径 5.6、琥珀の灯 8 つ、四隅の留め具（形 3〜6）から上の梁へ腕）。'
             '頭の上の物（跳んで届かない）。原点：台座の真ん中の床')
    z = 3.4
    R0 = 2.8
    ring = [(R0 * math.cos(2 * math.pi * k / 40), R0 * math.sin(2 * math.pi * k / 40), z) for k in range(41)]
    p.sweep(G, ring, 0.16, 8)
    ring2 = [(R0 * math.cos(2 * math.pi * k / 40), R0 * math.sin(2 * math.pi * k / 40), z - 0.2) for k in range(41)]
    p.sweep(B, ring2, 0.06, 6)
    for k in range(8):
        a = 2 * math.pi * (k + 0.5) / 8
        x, y = R0 * math.cos(a), R0 * math.sin(a)
        p.cbox(G, (x, y, z - 0.25), (0.3, 0.3, 0.3), 0.05)
        p.box('amber', (x - 0.06, y - 0.06, z - 0.43), (x + 0.06, y + 0.06, z - 0.4))
    # 四隅の留め具（形 3〜6：(±1.838, ±1.838)、高さ 1.4〜2.8）の上から輪へ
    for sx in (-1, 1):
        for sy in (-1, 1):
            x, y = sx * 1.838, sy * 1.838
            p.cyl(G, (x, y, 2.8), (x * 1.08, y * 1.08, z - 0.1), 0.12, 8)
            p.cbox(B, (x, y, 2.86), (0.5, 0.5, 0.12), 0.04)
            # 留め具から天井へ（吊りの柱）
            p.cyl(G, (x * 1.08, y * 1.08, z + 0.1), (x * 1.08, y * 1.08, 8.0), 0.09, 8)
    return p


