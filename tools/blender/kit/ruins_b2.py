def wall(name='b2_wall'):
    p = Part(name, '配管の壁 2×0.35×4：両端に白磁の支柱（赤い非常灯・琥珀の小灯）、黒鉛の太い管 2 本（半分壁に埋めた形）、上下に細い管。'
             '下の管の下の板にさびの筋。原点：背面の下の端の中央')
    p.box('dark', (-1, -0.05, 0.36), (1, 0, 3.62))
    frame_rails(p)
    # 下の管の下の板（汚れた白磁。さびが垂れる）と、管の間の黒鉛の板
    p.box(IS, (-0.76, -0.1, 0.36), (0.76, -0.05, 1.05))
    for z in (1.42, 2.3):
        fat_pipe_x(p, -1.0, 1.0, z)
    # 細い管（上と下）と受け
    for z, r in ((3.38, 0.06), (0.5, 0.045)):
        p.cyl(G, (-1, -0.16, z), (1, -0.16, z), r, 6)
        for bx in (-0.5, 0.5):
            p.box(B, (bx - 0.03, -0.16, z - r - 0.03), (bx + 0.03, 0.0, z - r))
    p.cyl(G, (-1, -0.12, 3.12), (1, -0.12, 3.12), 0.04, 6)
    # 垂れたさび（下の管の下の板の前）
    for k, (x, L, w) in enumerate(((-0.42, 0.55, 0.07), (-0.1, 0.38, 0.05), (0.25, 0.62, 0.08), (0.55, 0.3, 0.05))):
        p.box('stain_rust', (x - w / 2, -0.115, 1.05 - L), (x + w / 2, -0.11, 1.05))
    b2_post(p, -0.88)
    b2_post(p, 0.88, red=False)
    return p


def wall_vent(name='b2_wall_vent'):
    p = Part(name, '配管の壁の別の区画 2×0.35×4：通風の格子の板、太い管 1 本と圧力計の箱。原点：背面の下の端の中央')
    p.box('dark', (-1, -0.05, 0.36), (1, 0, 3.62))
    frame_rails(p)
    # 通風の格子（黒鉛の枠と羽板）
    p.box(G, (-0.74, -0.16, 0.5), (0.74, -0.05, 1.7))
    for k in range(7):
        z = 0.62 + k * 0.155
        n0 = len(p.pieces)
        p.box(G, (-0.68, -0.03, -0.03), (0.68, 0.03, 0.03))
        p.transformed(apply(rot('x', 35), (0, -0.2, z)), n0)
    fat_pipe_x(p, -1.0, 1.0, 2.35)
    # 圧力計の箱（真鍮の縁、琥珀の目盛り）と縦の細い管
    p.cbox(G, (0.35, -0.2, 3.05), (0.36, 0.18, 0.36), 0.04)
    p.cyl(B, (0.35, -0.29, 3.05), (0.35, -0.31, 3.05), 0.13, 12)
    p.cyl('dark', (0.35, -0.305, 3.05), (0.35, -0.318, 3.05), 0.1, 12)
    p.box(A, (0.34, -0.325, 3.05), (0.36, -0.319, 3.14))
    p.cyl(G, (-0.45, -0.12, 0.36), (-0.45, -0.12, 3.62), 0.05, 8)
    p.cyl(G, (-0.3, -0.12, 0.36), (-0.3, -0.12, 3.62), 0.035, 8)
    b2_post(p, -0.88, red=False)
    b2_post(p, 0.88)
    return p


