def steam():
    p = Part('b2_steam', '蒸気（足し合わせの半透明。広がる筒 長さ 2.2 m）。原点：吹き出し口。rot [180, yaw, 0] で上へ吹き出す')

    def ring(z, w, d, x):
        return [(x + w * math.cos(2 * math.pi * (k + 0.5) / 8), d * math.sin(2 * math.pi * (k + 0.5) / 8), z) for k in range(8)]
    # 光の筋（kit_glow）と同じ材質の作り：UV.y = 1 - z。上の端（z = 0）が濃い → 逆さに作って、原点を下に置く
    # 光の筋（b1_shaft）と同じく、原点から下へ広がる形で作る（kit_glow は上の端が濃く、下へ fade_m で消える）。
    # 置くときは "rot": [180, yaw, 0] で上下を返す（吹き出し口が下、上へ広がって消える）
    p.tube('steam', [ring(0.0, 0.12, 0.12, 0.0), ring(-0.8, 0.35, 0.3, 0.08), ring(-1.6, 0.6, 0.5, 0.18), ring(-2.2, 0.75, 0.6, 0.25)])
    return p


def valve(name='b2_valve', s=1.0, back=0.25, rod=0.0):
    p = Part(name, f'弁の輪（直径 {0.92 * s:.2f} m）：赤い輪と 4 本の腕、真鍮の軸、黒鉛の取付箱。原点：壁の面・輪の中心の高さ。輪は壁から {back} m'
             + (f'。軸の途中から上へ {rod} m の吊りの棒' if rod else ''))
    y = -back
