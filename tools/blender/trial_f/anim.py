def T(yaw, pitch=(2.0, 1.0, 1.0), roll=0.0, head=0.8, hd_pitch=-2.0):
    """胴のひねり：yaw の合計を腰・背骨・胸に分け（0.36・0.24・0.40）、頭は逆へ回して正面に残す"""
    return dict(hr=(pitch[0], yaw * 0.36, 0.0), sp=(pitch[1], yaw * 0.24, 0.0), ch=(pitch[2], yaw * 0.40, roll),
                nk=(-pitch[2] * 0.4, -yaw * head * 0.4, 0.0), hd=(hd_pitch - pitch[0] * 0.5, -yaw * head * 0.6, 0.0))


def TW(yaw, pitch=(2.0, 1.0, 1.0), roll=(0.0, 0.0, 0.0), head=0.8, hd_pitch=-2.0):
    """胴のひねりを腰・背骨・胸に別々に書く（度）。斬りは腰を大きく回して引く。頭は逆へ回して的に残す"""
    tot = yaw[0] + yaw[1] + yaw[2]
    return dict(hr=(pitch[0], yaw[0], roll[0]), sp=(pitch[1], yaw[1], roll[1]), ch=(pitch[2], yaw[2], roll[2]),
                nk=(-pitch[2] * 0.4, -tot * head * 0.4, 0.0), hd=(hd_pitch - pitch[0] * 0.5, -tot * head * 0.6, 0.0))


