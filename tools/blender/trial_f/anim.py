def ease(u, kind):
    u = min(1.0, max(0.0, u))
    if kind == 'lin':
        return u
    if kind == 'io':
        return u * u * (3 - 2 * u)
    if kind == 'io2':
        return u * u * u * (u * (6 * u - 15) + 10)
    if isinstance(kind, tuple):
        k, p = kind
        if k == 'in':
            return u ** p
        if k == 'out':
            return 1 - (1 - u) ** p
    return u


def mix(a, b, t, key):
    if key in DIRS:
        return slerp_dir(a, b, t)
    if isinstance(a, (int, float)):
        return a * (1 - t) + b * t
    return tuple(np.asarray(a, dtype=float) * (1 - t) + np.asarray(b, dtype=float) * t)


class Clip:
    """keys = [(こま, 姿勢, つなぎ)]。lag = {道: こま}：正で遅れる（腕は遅れ、腰は先に）。func(t こま) があればそれが姿勢を返す"""

    def __init__(self, name, frames, keys=None, func=None, lag=None, loop=False, legs='ik', floor='above', abs_arms=False, groups=None):
        self.name, self.frames, self.keys, self.func = name, frames, keys, func
        self.lag, self.loop, self.legs, self.floor, self.abs_arms = lag or {}, loop, legs, floor, abs_arms

    def chan(self, key, t):
        ks = self.keys
        if t <= ks[0][0]:
            return ks[0][1][key]
        for (t0, p0, _e0), (t1, p1, e1) in zip(ks, ks[1:]):
            if t <= t1:
                u = ease((t - t0) / max(1e-9, t1 - t0), e1)
                return mix(p0[key], p1[key], u, key)
        return ks[-1][1][key]

    def pose(self, t):
        if self.func is not None:
            return self.func(t)
        out = {}
        for key in BASE:
            lg = LAG_GROUP.get(key)
            tt = t - self.lag.get(lg, 0.0) if lg else t
            tt = min(self.frames, max(0.0, tt))
            out[key] = self.chan(key, tt)
        return out


