"""haru_f：姿勢と 14 動作の定義（numpy だけ）。焼き込みは anim_bake.py。

座標は glTF と同じモデルの軸：X = 本人の左、Y = 上、Z = 正面。角度は度。
回転の向き：pitch（X まわり、正で前へ倒す）、yaw（Y まわり、正で左へ向く）、roll（Z まわり、正で右へ傾く）。
骨の向き（roll）には頼らない：骨ごとの回転 D をモデルの軸で書き、基準の姿勢から組む（M(骨) = M(親)・D）。
腕は「上腕の向き・前腕の向き・前腕の甲（外）の向き」で書く（胸に付いた座標。abs_arms の動作ではモデルの座標）。
脚は足の置き場所から IK（legs='ik'）、空中・倒れは回転で書く（legs='fk'）。
"""
from __future__ import annotations

import math

import numpy as np

FPS = 60
V = lambda *a: np.array(a, dtype=float)


def nrm(v):
    v = np.asarray(v, dtype=float)
    n = np.linalg.norm(v)
    return v / n if n > 1e-12 else v


def rx(d):
    a = math.radians(d); c, s = math.cos(a), math.sin(a)
    return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])


def ry(d):
    a = math.radians(d); c, s = math.cos(a), math.sin(a)
    return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])


def rz(d):
    a = math.radians(d); c, s = math.cos(a), math.sin(a)
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


def euler(e):
    """(pitch, yaw, roll) → 回転行列。yaw が外、roll が内。roll は正で右へ傾く"""
    return ry(e[1]) @ rx(e[0]) @ rz(e[2])


def frame(u, f):
    """u（骨の向き）と f（曲げる側・甲の側の目安）から直交の枠 [s f u]"""
    u = nrm(u)
    f = np.asarray(f, dtype=float)
    f = f - u * np.dot(f, u)
    if np.linalg.norm(f) < 1e-6:
        f = V(0, 0, 1) - u * u[2]
        if np.linalg.norm(f) < 1e-6:
            f = V(0, 1, 0) - u * u[1]
    f = nrm(f)
    s = np.cross(f, u)
    return np.stack([s, f, u], axis=1)


def slerp_dir(a, b, t):
    a, b = nrm(a), nrm(b)
    d = float(np.clip(np.dot(a, b), -1, 1))
    th = math.acos(d)
    if th < 1e-4:
        return nrm(a * (1 - t) + b * t)
    if th > math.pi - 1e-3:
        return nrm(a * (1 - t) + b * t + V(1e-3, 0, 0))
    return (math.sin((1 - t) * th) * a + math.sin(t * th) * b) / math.sin(th)


