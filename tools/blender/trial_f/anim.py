def _run_foot(p):
    """走りの足：位相 p（0〜1）。接地 0〜0.36、あとは振り出し。戻り値 (z, y, pitch)"""
    if p < 0.36:
        u = p / 0.36
        z = 0.30 - 0.66 * u
        if u < 0.2:
            pitch = -12.0 * (1 - u / 0.2)
        elif u > 0.55:
            pitch = 42.0 * ((u - 0.55) / 0.45) ** 1.4
        else:
            pitch = 0.0
        return z, 0.0, pitch
    u = (p - 0.36) / 0.64
    z = -0.36 + 0.66 * (u * u * (3 - 2 * u))
    y = 0.27 * math.sin(math.pi * u) ** 0.9 * (1 - 0.5 * u)
    pitch = 42.0 + 30.0 * (u / 0.3) if u < 0.3 else 72.0 - 84.0 * ((u - 0.3) / 0.7) ** 0.9
    return z, y, pitch


def run_pose(t):
    T = 40.0
    ph = (t / T) % 1.0
    zl, yl, pl = _run_foot(ph)
    zr, yr, pr = _run_foot((ph + 0.5) % 1.0)
    w = math.sin(2 * math.pi * (ph - 0.07))         # +1 で左足が前
    bob = math.cos(4 * math.pi * (ph - 0.09))
    aL = -38.0 * w + 4.0                            # 左腕の振り（前が正）。左足が前のとき後ろ
    aR = 24.0 * w + 14.0                            # 銃の腕は控えめ
    eL = 78.0 + 14.0 * (-w)
    eR = 86.0

    def arm(side, a, e):
        ar, er = math.radians(a), math.radians(a + e)
        up = (side * 0.20, -math.cos(ar), math.sin(ar))
        fo = (-side * 0.16 + side * 0.10 * (a < 0), -math.cos(er), math.sin(er))
        return up, fo
    lu, lf = arm(1, aL, eL)
    ru, rf = arm(-1, aR, eR)
    return P(hp=(0.0, -0.058 + 0.026 * bob, 0.03), hr=(13.0, -9.0 * w, 2.5 * w),
             sp=(5.0, 6.0 * w, -1.5 * w), ch=(5.0, 12.0 * w, -1.5 * w), nk=(-5.0, -4.0 * w, 0.0), hd=(-9.0, -5.0 * w, 0.0),
             aLu=lu, aLf=lf, aLo=(0.97, 0.10, 0.10), aRu=ru, aRf=rf, aRo=(-0.97, 0.10, 0.10),
             fL=(-0.045, yl, zl), fLr=(pl, 0.0, 0.0), fR=(0.045, yr, zr), fRr=(pr, 0.0, 0.0))


